export type MessageKey = keyof (typeof messages)["zh"];

export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}

export function relativeTime(from: number, now: number, locale: Locale): string {
  const text = messages[locale];
  const seconds = Math.max(0, Math.round((now - from) / 1000));
  if (seconds < 5) return text.justNow;
  if (seconds < 60) return fill(text.secondsAgo, { n: seconds });
  const minutes = Math.round(seconds / 60);
  if (minutes < 60) return fill(text.minutesAgo, { n: minutes });
  const hours = Math.round(minutes / 60);
  if (hours < 48) return fill(text.hoursAgo, { n: hours });
  return fill(text.daysAgo, { n: Math.round(hours / 24) });
}

export function formatCountdown(ms: number, locale: Locale): string {
  if (ms <= 0) return messages[locale].dueNow;
  const total = Math.floor(ms / 1000);
  const days = Math.floor(total / 86400);
  const hours = Math.floor((total % 86400) / 3600);
  const minutes = Math.floor((total % 3600) / 60);
  const seconds = total % 60;
  const pad = (value: number) => String(value).padStart(2, "0");
  const clock = `${pad(hours)}:${pad(minutes)}:${pad(seconds)}`;
  if (days > 0) return locale === "zh" ? `${days}天 ${clock}` : `${days}d ${clock}`;
  return clock;
}
